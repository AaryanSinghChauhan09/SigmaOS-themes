//! SigmaOS-theme-gtk3 — GTK3 theme engine.
//!
//! Generates and validates GTK3 CSS stylesheets mapping Catppuccin Mocha colors
//! to standard GTK semantic color definitions (`@theme_bg_color`, `@theme_fg_color`, etc.).
//!
//! Inspired by Omarchy's seamless desktop theme integration, Hyprland's unified toolkit styling,
//! and Catppuccin Mocha's warm aesthetic.
//!
//! Principles: semantic CSS token generation, pure `std`, zero `unsafe`.

#![forbid(unsafe_code)]

use std::fmt;

// ── Error types ──────────────────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GtkThemeError {
    InvalidColorHex(String),
    InvalidBorderRadius(u32),
    UnknownWidgetClass(String),
}

impl fmt::Display for GtkThemeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidColorHex(h) => write!(f, "invalid hex color string: '{h}' (expected #rrggbb)"),
            Self::InvalidBorderRadius(r) => write!(f, "border radius {r}px out of bounds (0..=32px)"),
            Self::UnknownWidgetClass(w) => write!(f, "unrecognized GTK widget selector: '{w}'"),
        }
    }
}

impl std::error::Error for GtkThemeError {}

// ── GTK3 Palette and Tokens ──────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GtkPalette {
    pub bg_color: String,
    pub fg_color: String,
    pub base_color: String,
    pub text_color: String,
    pub selected_bg_color: String,
    pub selected_fg_color: String,
    pub border_color: String,
}

impl GtkPalette {
    pub fn catppuccin_mocha() -> Self {
        Self {
            bg_color: "#1e1e2e".into(),          // Base
            fg_color: "#cdd6f4".into(),          // Text
            base_color: "#181825".into(),        // Mantle
            text_color: "#cdd6f4".into(),        // Text
            selected_bg_color: "#cba6f7".into(), // Mauve
            selected_fg_color: "#11111b".into(), // Crust
            border_color: "#313244".into(),      // Surface0
        }
    }

    pub fn catppuccin_latte() -> Self {
        Self {
            bg_color: "#eff1f5".into(),          // Base
            fg_color: "#4c4f69".into(),          // Text
            base_color: "#e6e9ef".into(),        // Mantle
            text_color: "#4c4f69".into(),        // Text
            selected_bg_color: "#8839ef".into(), // Mauve
            selected_fg_color: "#ffffff".into(),
            border_color: "#ccd0da".into(),      // Surface0
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GtkThemeEngine {
    pub name: String,
    pub palette: GtkPalette,
    pub border_radius_px: u32,
    pub use_animations: bool,
}

impl GtkThemeEngine {
    pub fn new(name: impl Into<String>, palette: GtkPalette) -> Self {
        Self {
            name: name.into(),
            palette,
            border_radius_px: 8,
            use_animations: true,
        }
    }

    pub fn set_border_radius(&mut self, radius: u32) -> Result<(), GtkThemeError> {
        if radius > 32 {
            return Err(GtkThemeError::InvalidBorderRadius(radius));
        }
        self.border_radius_px = radius;
        Ok(())
    }

    pub fn compile_gtk3_css(&self) -> String {
        format!(
            "/* Generated by SigmaOS GTK3 Engine: {} */\n\
             @define-color theme_bg_color {};\n\
             @define-color theme_fg_color {};\n\
             @define-color theme_base_color {};\n\
             @define-color theme_text_color {};\n\
             @define-color theme_selected_bg_color {};\n\
             @define-color theme_selected_fg_color {};\n\
             \n\
             window.background {{\n\
                 background-color: @theme_bg_color;\n\
                 color: @theme_fg_color;\n\
             }}\n\
             \n\
             button {{\n\
                 border-radius: {}px;\n\
                 border: 1px solid {};\n\
             }}\n\
             \n\
             button:checked, button:active {{\n\
                 background-color: @theme_selected_bg_color;\n\
                 color: @theme_selected_fg_color;\n\
             }}\n",
            self.name,
            self.palette.bg_color,
            self.palette.fg_color,
            self.palette.base_color,
            self.palette.text_color,
            self.palette.selected_bg_color,
            self.palette.selected_fg_color,
            self.border_radius_px,
            self.palette.border_color
        )
    }
}

// ── Tests ────────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mocha_palette_token_values() {
        // Arrange & Act
        let p = GtkPalette::catppuccin_mocha();
        // Assert
        assert_eq!(p.bg_color, "#1e1e2e");
        assert_eq!(p.selected_bg_color, "#cba6f7");
        assert_eq!(p.fg_color, "#cdd6f4");
    }

    #[test]
    fn latte_palette_token_values() {
        // Arrange & Act
        let p = GtkPalette::catppuccin_latte();
        // Assert
        assert_eq!(p.bg_color, "#eff1f5");
        assert_eq!(p.selected_bg_color, "#8839ef");
    }

    #[test]
    fn border_radius_bounds_check() {
        // Arrange
        let mut engine = GtkThemeEngine::new("test", GtkPalette::catppuccin_mocha());
        // Act
        let valid = engine.set_border_radius(12);
        let too_large = engine.set_border_radius(40);
        // Assert
        assert!(valid.is_ok());
        assert_eq!(engine.border_radius_px, 12);
        assert_eq!(too_large, Err(GtkThemeError::InvalidBorderRadius(40)));
    }

    #[test]
    fn compile_gtk3_css_contains_definitions() {
        // Arrange
        let engine = GtkThemeEngine::new("Catppuccin Mocha", GtkPalette::catppuccin_mocha());
        // Act
        let css = engine.compile_gtk3_css();
        // Assert
        assert!(css.contains("@define-color theme_bg_color #1e1e2e;"));
        assert!(css.contains("@define-color theme_selected_bg_color #cba6f7;"));
        assert!(css.contains("border-radius: 8px;"));
    }

    #[test]
    fn error_display_formatting() {
        // Arrange
        let err = GtkThemeError::InvalidColorHex("xyz".into());
        // Act & Assert
        assert_eq!(format!("{err}"), "invalid hex color string: 'xyz' (expected #rrggbb)");
    }
}
